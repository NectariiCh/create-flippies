plugins {
    id("net.neoforged.moddev.legacyforge")
    `maven-publish`
}

apply(from = rootProject.file("build.common.gradle.kts"))

val modId = property("mod_id") as String
val mcVersion = property("minecraft_version") as String

java.toolchain.languageVersion = JavaLanguageVersion.of(17)

legacyForge {
    version = "$mcVersion-${property("forge_version")}"

    // SRG names: Forge 1.20.1 reads only this fixed path. MDG finds it in main's resources.
    validateAccessTransformers = true

    runs {
        configureEach {
            // run/ is the folder the single-project build used, so existing worlds and configs stay
            gameDirectory = rootProject.file("run")
            systemProperty("forge.logging.markers", "REGISTRIES")
            systemProperty("forge.logging.console.level", "debug")
            // MDG sets mixin.env.remapRefMap and mixin.env.refMapRemappingFile itself, which
            // dependency mods that ship mixins (Create, Power Grid, Architectury) need here.
        }
        register("client") {
            client()
            systemProperty("forge.enabledGameTestNamespaces", modId)
        }
        register("server") {
            server()
            systemProperty("forge.enabledGameTestNamespaces", modId)
            programArgument("--nogui")
        }
        register("gameTestServer") {
            type = "gameTestServer"
            systemProperty("forge.enabledGameTestNamespaces", modId)
        }
        register("data") {
            data()
            gameDirectory = rootProject.file("run-data")
            programArguments.addAll(
                "--mod", modId, "--all",
                "--output", rootProject.file("src/generated/resources").absolutePath,
                "--existing", rootProject.file("src/main/resources").absolutePath,
            )
        }
    }

    mods { register(modId) { sourceSet(sourceSets.main.get()) } }
}

// Minecraft classes for the tests that use CompoundTag, Vec3, PoseStack and the like.
legacyForge { addModdingDependenciesTo(sourceSets.test.get()) }

// Include resources generated by data generators.
sourceSets.main { resources.srcDir(rootProject.file("src/generated/resources")) }

// Builds this mod's mixin refmap (SRG names) and packs it into the jar, as MixinGradle did.
mixin {
    add(sourceSets.main.get(), "$modId.refmap.json")
    config("$modId.mixins.json")
}

dependencies {
    // Generates this mod's mixin refmap at compile time (mixin itself ships with Forge)
    annotationProcessor("org.spongepowered:mixin:${property("mixin_version")}:processor")

    // The mod* configurations remap these SRG jars to official names, the job fg.deobf did.
    // They are not transitive.

    // Create and its libraries
    modImplementation("com.simibubi.create:create-$mcVersion:${property("create_version")}:slim")
    modImplementation("net.createmod.ponder:Ponder-Forge-$mcVersion:${property("ponder_version")}")
    modImplementation("dev.engine-room.flywheel:flywheel-forge-$mcVersion:${property("flywheel_version")}")
    modImplementation("com.tterrag.registrate:Registrate:${property("registrate_version")}")

    // Create: Power Grid (the mod this addon extends) and its Architectury runtime
    modImplementation("maven.modrinth:power-grid:${property("powergrid_version")}")
    modImplementation("dev.architectury:architectury-forge:${property("architectury_version")}")

    // Hypergraphical Lib, built from the local clone in hypergraphical-lib/ (see
    // settings.gradle.kts). It is a source build in official mappings, so plain implementation:
    // MDG picks its unobfuscated jar. Embeddium is its hard requirement and is only needed to
    // run the game here.
    implementation("dev.nectariich.hypergraphical:hypergraphical-forge:${property("hypergraphical_version")}+mc$mcVersion")
    modRuntimeOnly("maven.modrinth:embeddium:${property("embeddium_version")}")
}

tasks.processResources {
    exclude("META-INF/neoforge.mods.toml")
}

// Forge 1.20.1 loads mixin configs only through this manifest attribute. MixinGradle added it;
// MDG does not.
tasks.jar {
    manifest.attributes("MixinConfigs" to "$modId.mixins.json")
}

publishing.publications.named<MavenPublication>("mavenJava") {
    artifact(tasks.named("reobfJar"))
}

tasks.named("createMinecraftArtifacts") { dependsOn("stonecutterGenerate") }
