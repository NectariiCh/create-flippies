plugins {
    id("net.neoforged.moddev")
    `maven-publish`
}

apply(from = rootProject.file("build.common.gradle.kts"))

val modId = property("mod_id") as String
val mcVersion = property("minecraft_version") as String

java.toolchain.languageVersion = JavaLanguageVersion.of(21)

repositories {
    // Registrate for 1.21 is published only here
    exclusiveContent {
        forRepository { maven("https://maven.ithundxr.dev/snapshots") { name = "ithundxr snapshots" } }
        filter { includeGroup("com.tterrag.registrate") }
    }
}

neoForge {
    version = property("neoforge_version") as String

    // META-INF/accesstransformer.cfg is in SRG names for Forge 1.20.1. NeoForge and Power Grid
    // 1.21.1 already make getEntities() public, so this node uses no access transformer.
    setAccessTransformers()
    validateAccessTransformers = true

    runs {
        configureEach {
            gameDirectory = rootProject.file("run/1.21.1-neoforge")
            systemProperty("forge.logging.markers", "REGISTRIES")
            systemProperty("forge.logging.console.level", "debug")
        }
        register("client") {
            client()
            systemProperty("neoforge.enabledGameTestNamespaces", modId)
        }
        register("server") {
            server()
            systemProperty("neoforge.enabledGameTestNamespaces", modId)
            programArgument("--nogui")
        }
        register("gameTestServer") {
            type = "gameTestServer"
            systemProperty("neoforge.enabledGameTestNamespaces", modId)
        }
        // Writes 1.21.1-format data, so into this node's own folder rather than the shared
        // src/generated/resources the Forge node reads.
        register("data") {
            data()
            gameDirectory = rootProject.file("run-data/1.21.1-neoforge")
            programArguments.addAll(
                "--mod", modId, "--all",
                "--output", file("src/generated/resources").absolutePath,
                "--existing", rootProject.file("src/main/resources").absolutePath,
            )
        }
    }

    mods { register(modId) { sourceSet(sourceSets.main.get()) } }
}

// Minecraft classes for the tests that use CompoundTag, Vec3, PoseStack and the like.
neoForge { addModdingDependenciesTo(sourceSets.test.get()) }

// Include resources generated by this node's data generators.
sourceSets.main { resources.srcDir(file("src/generated/resources")) }

dependencies {
    // 1.21.1 mods are published in Mojang names, so no remapping. Create's POM lists its
    // optional integrations (JEI, Curios, ...), hence non-transitive.

    // Create and its libraries, the versions Create 6.0.10 bundles
    implementation("com.simibubi.create:create-$mcVersion:${property("create_version")}:slim") { isTransitive = false }
    implementation("net.createmod.ponder:ponder-neoforge:${property("ponder_version")}") { isTransitive = false }
    implementation("dev.engine-room.flywheel:flywheel-neoforge-$mcVersion:${property("flywheel_version")}") { isTransitive = false }
    implementation("com.tterrag.registrate:Registrate:${property("registrate_version")}")

    // Create: Power Grid and its Architectury runtime
    implementation("maven.modrinth:power-grid:${property("powergrid_version")}")
    implementation("dev.architectury:architectury-neoforge:${property("architectury_version")}")

    // Hypergraphical Lib, the included build's 1.21.1 node. Sodium is its hard requirement
    // on 1.21.1 and is only needed to run the game here.
    implementation("dev.nectariich.hypergraphical:hypergraphical-neoforge:${property("hypergraphical_version")}+mc$mcVersion")
    runtimeOnly("maven.modrinth:sodium:${property("sodium_version")}")
}

tasks.processResources {
    exclude("META-INF/mods.toml", "META-INF/accesstransformer.cfg", "pack.mcmeta")
    includeEmptyDirs = false

    // 1.21.1 runs Mojang names in production: no refmap is generated, so drop the key
    filesMatching("$modId.mixins.json") {
        filter { line -> if (line.contains("\"refmap\"")) "" else line }
    }

    // src/main/resources is in the 1.20.1 layout; 1.21 renamed these data folders
    eachFile {
        path = when (path) {
            "data/forge/tags/items/wires.json" -> "data/c/tags/item/wires.json"
            else -> path
                .replaceFirst(Regex("^data/([^/]+)/loot_tables/"), "data/$1/loot_table/")
                .replaceFirst(Regex("^data/([^/]+)/tags/items/"), "data/$1/tags/item/")
                .replaceFirst(Regex("^data/([^/]+)/tags/blocks/"), "data/$1/tags/block/")
        }
    }
}


publishing.publications.named<MavenPublication>("mavenJava") {
    artifact(tasks.jar)
}

tasks.named("createMinecraftArtifacts") { dependsOn("stonecutterGenerate") }
